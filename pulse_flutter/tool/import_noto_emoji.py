#!/usr/bin/env python3
"""Vendor Google's Noto font and animations; never fetch emoji at runtime.

Refresh intentionally: python tool/import_noto_emoji.py --refresh
Verify offline:       python tool/import_noto_emoji.py --verify
Restore pinned files: python tool/import_noto_emoji.py

The default mode checks the committed manifest's SHA-256 before writing any
replacement. A changed upstream ``latest`` asset therefore needs an explicit,
reviewable refresh. Gzip output is deterministic (mtime=0, empty filename).
"""

from __future__ import annotations

import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
import gzip
import hashlib
import io
import json
import math
from pathlib import Path
import threading
import time
import urllib.error
import urllib.request


ROOT = Path(__file__).resolve().parents[1]
MANIFEST_PATH = ROOT / "assets/emoji/noto_emoji_manifest.json"
CATALOG_PATH = ROOT / "lib/core/utils/noto_emoji_catalog.dart"
FONT_REVISION = "e20cbc2bbec1926686be9f9bee7d1d2cfa1fea0e"
FONT_ROOT = (
    "https://raw.githubusercontent.com/googlefonts/noto-emoji/"
    f"{FONT_REVISION}/2D/fonts/"
)
STATIC_METADATA_URL = (
    "https://googlefonts.github.io/noto-emoji-files/data/"
    "emojis_data.js?v=20260916_v7"
)
ANIMATION_METADATA_URL = (
    "https://googlefonts.github.io/noto-emoji-animation/data/api.json"
)
ANIMATION_BASE = "https://fonts.gstatic.com/s/e/notoemoji/latest/"
CC_BY_URL = "https://creativecommons.org/licenses/by/4.0/legalcode.txt"
APACHE_URL = "https://www.apache.org/licenses/LICENSE-2.0.txt"
MAX_ANIMATION_BYTES = 50 * 1024 * 1024
MAX_SOURCE_BYTES = 16 * 1024 * 1024
MAX_ASSET_BYTES = 4 * 1024 * 1024


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def deterministic_gzip(data: bytes) -> bytes:
    # gzip.compress(..., mtime=0) uses a platform-dependent OS header in Python
    # 3.11/3.12. GzipFile produces OS=255 on Windows and CI/Linux alike.
    output = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=output, compresslevel=9, mtime=0) as stream:
        stream.write(data)
    return output.getvalue()


def fetch(url: str, max_bytes: int = MAX_SOURCE_BYTES) -> bytes:
    """Download bounded public HTTPS resources without credentials."""
    if not url.startswith("https://"):
        raise ValueError("Only public HTTPS sources are allowed")
    for attempt in range(3):
        try:
            request = urllib.request.Request(
                url, headers={"User-Agent": "NiosMess-Noto-Asset-Importer/1.0"}
            )
            with urllib.request.urlopen(request, timeout=40) as response:
                data = response.read(max_bytes + 1)
            if len(data) > max_bytes:
                raise ValueError(f"Oversized upstream resource: {url}")
            return data
        except (urllib.error.URLError, TimeoutError):
            if attempt == 2:
                raise
            time.sleep(attempt + 1)
    raise AssertionError("Unreachable download state")


def canonical_id(value: str) -> str:
    codepoints = [int(part, 16) for part in value.lower().split("_")]
    if not codepoints or any(point > 0x10FFFF for point in codepoints):
        raise ValueError(f"Invalid Unicode sequence: {value}")
    return "_".join(f"{point:x}" for point in codepoints if point != 0xFE0F)


def cdn_id(value: str) -> str:
    # The official CDN pads BMP values to four hex digits, unlike the older
    # animation index (a9_fe0f -> 00a9_fe0f). Keep FE0F in the source URL.
    return "_".join(f"{int(part, 16):04x}" for part in value.split("_"))


def is_public_unicode_sequence(value: str) -> bool:
    """Exclude Google's legacy private-use glyph, not real Unicode emoji."""
    for point in (int(part, 16) for part in value.split("_")):
        if (
            0xE000 <= point <= 0xF8FF
            or 0xF0000 <= point <= 0xFFFFD
            or 0x100000 <= point <= 0x10FFFD
        ):
            return False
    return True


def asset_path(relative: str) -> Path:
    path = (ROOT / relative).resolve()
    if not path.is_relative_to(ROOT.resolve()):
        raise ValueError(f"Asset escaped project: {relative}")
    return path


def write_if_changed(path: Path, data: bytes) -> None:
    if path.is_file() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_bytes(data)
    temporary.replace(path)


def catalog_bytes(emoji_ids: list[str], animation_ids: list[str]) -> bytes:
    lines = [
        "// Generated by tool/import_noto_emoji.py. Do not edit manually.",
        "// Google's Noto metadata; Unicode IDs omit emoji presentation FE0F.",
        "// Source attribution: assets/licenses/noto-emoji-metadata.txt.",
        "",
    ]
    for name, values in (
        ("notoEmojiIds", emoji_ids),
        ("animatedNotoEmojiIds", animation_ids),
    ):
        lines.append(f"const Set<String> {name} = <String>{{")
        lines.extend(f"  '{value}'," for value in values)
        lines.extend(["};", ""])
    return "\n".join(lines).encode("utf-8")


def plain_asset(path: str, url: str, data: bytes) -> dict:
    write_if_changed(asset_path(path), data)
    return {"path": path, "url": url, "sha256": sha256(data), "bytes": len(data)}


def validate_animation(data: bytes, source_id: str) -> None:
    animation = json.loads(data)
    if not isinstance(animation.get("layers"), list):
        raise ValueError(f"Invalid Lottie layers: {source_id}")
    for key in ("w", "h", "fr", "ip", "op"):
        value = animation.get(key)
        if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
            raise ValueError(f"Invalid Lottie {key}: {source_id}")
    if (
        min(animation["w"], animation["h"], animation["fr"]) <= 0
        or animation["op"] <= animation["ip"]
    ):
        raise ValueError(f"Invalid Lottie frame bounds: {source_id}")
    if animation.get("fonts") or animation.get("chars"):
        raise ValueError(f"Non-vector Lottie font/glyph reference: {source_id}")
    for asset in animation.get("assets", []):
        # Vector precompositions are expected. Raster/embedded/external image
        # references are deliberately disallowed: nothing may fetch at runtime.
        if asset.get("p") or asset.get("u") or asset.get("e"):
            raise ValueError(f"Non-self-contained Lottie image asset: {source_id}")


def license_notice(path: str, original_license: bytes) -> bytes:
    if path == "assets/licenses/noto-emoji-animation.txt":
        prefix = (
            "Animated Noto Emoji by Google\n"
            "Source: https://googlefonts.github.io/noto-emoji-files/\n"
            "Original files: https://fonts.gstatic.com/s/e/notoemoji/latest/\n"
            "License: Creative Commons Attribution 4.0 International (CC BY 4.0)\n"
            "License URL: https://creativecommons.org/licenses/by/4.0/\n\n"
            "NiosMess packages the original Lottie JSON in deterministic gzip files.\n"
            "The artwork, colors, timing and animation data have not been changed.\n\n"
        )
    elif path == "assets/licenses/noto-emoji-metadata.txt":
        prefix = (
            "Noto Emoji metadata by Google LLC\n"
            "Source: https://github.com/googlefonts/noto-emoji\n"
            "Catalog: https://googlefonts.github.io/noto-emoji-files/\n"
            "Animation index: " + ANIMATION_METADATA_URL + "\n\n"
            "NiosMess extracts Unicode codepoint identifiers only. Emoji presentation\n"
            "selector FE0F is omitted for lookup, while all ZWJ, tone, tag, gender and\n"
            "flag codepoints remain intact. The legacy private-use glyph is excluded.\n\n"
            "Copyright 2013 Google, Inc. All Rights Reserved.\n"
            "Licensed under the Apache License, Version 2.0.\n\n"
        )
    else:
        return original_license
    return prefix.encode("utf-8") + original_license.rstrip(b"\r\n") + b"\n"


def refresh(workers: int) -> dict:
    static_source = fetch(STATIC_METADATA_URL)
    prefix = b"window.__NOTO_EMOJIS_DATA__ = "
    if not static_source.startswith(prefix):
        raise ValueError("Google changed the static metadata format")
    static_data = json.loads(static_source[len(prefix):].strip().rstrip(b";"))
    animation_source = fetch(ANIMATION_METADATA_URL)
    animation_data = json.loads(animation_source)
    emoji_ids = sorted(
        {
            canonical_id(item["codepoint"])
            for item in static_data
            if is_public_unicode_sequence(item["codepoint"])
        }
    )
    animations = {}
    for item in animation_data["icons"]:
        source_id = item["codepoint"]
        normalized = canonical_id(source_id)
        if normalized in animations:
            raise ValueError(f"Duplicate normalized animation: {normalized}")
        if normalized not in emoji_ids:
            raise ValueError(f"Animation missing from Noto metadata: {normalized}")
        animations[normalized] = source_id
    if len(emoji_ids) < 3000 or len(animations) < 700:
        raise ValueError("Unexpectedly incomplete Google metadata")

    font = fetch(FONT_ROOT + "NotoColorEmoji.ttf")
    font_license = fetch(FONT_ROOT + "LICENSE")
    cc_license = fetch(CC_BY_URL)
    apache_license = fetch(APACHE_URL)
    animation_notice = license_notice("assets/licenses/noto-emoji-animation.txt", cc_license)
    metadata_notice = license_notice("assets/licenses/noto-emoji-metadata.txt", apache_license)
    assets = [
        plain_asset(
            "assets/fonts/noto_color_emoji/NotoColorEmoji.ttf",
            FONT_ROOT + "NotoColorEmoji.ttf",
            font,
        ),
        plain_asset("assets/licenses/noto-emoji-font.txt", FONT_ROOT + "LICENSE", font_license),
        plain_asset("assets/licenses/noto-emoji-animation.txt", CC_BY_URL, animation_notice),
        plain_asset("assets/licenses/noto-emoji-metadata.txt", APACHE_URL, metadata_notice),
    ]
    size_lock = threading.Lock()
    total_compressed = 0

    def import_animation(pair: tuple[str, str]) -> dict:
        nonlocal total_compressed
        normalized, source_id = pair
        url = ANIMATION_BASE + cdn_id(source_id) + "/lottie.json"
        original = fetch(url, MAX_ASSET_BYTES)
        validate_animation(original, source_id)
        compressed = deterministic_gzip(original)
        with size_lock:
            total_compressed += len(compressed)
            if total_compressed > MAX_ANIMATION_BYTES:
                raise ValueError("Animations exceed the 50 MiB review threshold")
        path = f"assets/emoji/animated/{normalized}.json.gz"
        write_if_changed(asset_path(path), compressed)
        return {
            "id": normalized,
            "source_id": source_id,
            "path": path,
            "url": url,
            "sha256": sha256(original),
            "gzip_sha256": sha256(compressed),
            "source_bytes": len(original),
            "gzip_bytes": len(compressed),
        }

    entries = []
    with ThreadPoolExecutor(max_workers=workers) as executor:
        futures = [executor.submit(import_animation, pair) for pair in animations.items()]
        for future in as_completed(futures):
            entries.append(future.result())
            if len(entries) % 100 == 0:
                print(f"Imported {len(entries)}/{len(animations)} animations", flush=True)
    entries.sort(key=lambda item: item["id"])
    expected_files = {entry["path"] for entry in entries}
    animation_dir = ROOT / "assets/emoji/animated"
    for stale in animation_dir.glob("*.json.gz"):
        if stale.relative_to(ROOT).as_posix() not in expected_files:
            stale.unlink()
    manifest = {
        "schema_version": 1,
        "font_revision": FONT_REVISION,
        "sources": [
            {"url": STATIC_METADATA_URL, "sha256": sha256(static_source)},
            {"url": ANIMATION_METADATA_URL, "sha256": sha256(animation_source)},
        ],
        "emoji_ids": emoji_ids,
        "assets": assets,
        "animations": entries,
    }
    write_if_changed(CATALOG_PATH, catalog_bytes(emoji_ids, [entry["id"] for entry in entries]))
    write_if_changed(
        MANIFEST_PATH,
        (json.dumps(manifest, indent=2, ensure_ascii=True) + "\n").encode(),
    )
    return manifest


def verify_or_restore(manifest: dict, verify_only: bool, workers: int) -> None:
    if manifest.get("schema_version") != 1:
        raise ValueError("Unknown Noto asset manifest version")

    def check(entry: dict, animation: bool = False) -> None:
        path = asset_path(entry["path"])
        expected = entry["gzip_sha256"] if animation else entry["sha256"]
        if path.is_file() and sha256(path.read_bytes()) == expected:
            return
        if verify_only:
            raise ValueError(f"Missing or modified vendored file: {entry['path']}")
        downloaded = license_notice(entry["path"], fetch(entry["url"]))
        if sha256(downloaded) != entry["sha256"]:
            raise ValueError(f"Upstream asset changed; review --refresh: {entry['path']}")
        if animation:
            validate_animation(downloaded, entry["id"])
        data = deterministic_gzip(downloaded) if animation else downloaded
        if sha256(data) != expected:
            raise ValueError(f"Non-reproducible compression: {entry['path']}")
        write_if_changed(path, data)

    entries = [(entry, False) for entry in manifest["assets"]]
    entries.extend((entry, True) for entry in manifest["animations"])
    with ThreadPoolExecutor(max_workers=workers) as executor:
        list(executor.map(lambda pair: check(*pair), entries))
    animation_ids = [entry["id"] for entry in manifest["animations"]]
    expected_catalog = catalog_bytes(manifest["emoji_ids"], animation_ids)
    if verify_only:
        if CATALOG_PATH.read_bytes() != expected_catalog:
            raise ValueError("Generated Noto Unicode catalog does not match manifest")
        for entry in manifest["animations"]:
            original = gzip.decompress(asset_path(entry["path"]).read_bytes())
            if sha256(original) != entry["sha256"]:
                raise ValueError(f"Lottie source checksum mismatch: {entry['id']}")
            validate_animation(original, entry["id"])
    else:
        write_if_changed(CATALOG_PATH, expected_catalog)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--refresh", action="store_true", help="Reviewably update Google's pinned assets")
    mode.add_argument("--verify", action="store_true", help="Verify all vendored files offline")
    parser.add_argument("--workers", type=int, default=12)
    args = parser.parse_args()
    if not 1 <= args.workers <= 24:
        parser.error("workers must be between 1 and 24")
    if args.refresh:
        manifest = refresh(args.workers)
    else:
        if not MANIFEST_PATH.is_file():
            parser.error("No pinned manifest; run --refresh for the first import")
        manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
        verify_or_restore(manifest, args.verify, args.workers)
    compressed_bytes = sum(entry["gzip_bytes"] for entry in manifest["animations"])
    print(
        f"Verified {len(manifest['emoji_ids'])} Unicode IDs, "
        f"{len(manifest['animations'])} animations ({compressed_bytes:,} gzip bytes), "
        "and Noto Color Emoji font/licenses.",
        flush=True,
    )


if __name__ == "__main__":
    main()
